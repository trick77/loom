package llm

import (
	"bytes"
	"context"
	"encoding/base64"
	"fmt"
	"strings"
	"time"

	"github.com/trick77/loom/internal/imagescale"
	"github.com/trick77/loom/internal/inference"
	"github.com/trick77/toolkit/llmwire"
)

// imageDescribeMaxCompletionTokens caps the vision description. At the helper
// effort nearly the whole budget goes to the description itself, so a few dense
// paragraphs incl. transcribed text fit in 2048.
const imageDescribeMaxCompletionTokens = 2048

// imageDescribeTimeout bounds a single description call. Ingest runs detached
// (context.WithoutCancel) and main passes an untimed http client, so without this
// a stalled vision turn would hang the ingest goroutine indefinitely.
const imageDescribeTimeout = 2 * time.Minute

const imageDescribeInstruction = "Describe this image in detail for a search index. " +
	"Cover the main subjects, scene, layout, colors, and any visible or legible text " +
	"verbatim. Write plain descriptive prose with no preamble, no markdown, and no questions."

// imageAskMaxCompletionTokens caps the answer to a question about an image: a
// few sentences naming what is seen (axis ranges, labels, layout).
const imageAskMaxCompletionTokens = 1024

// imageAskTimeout bounds one question about an image. A turn waits on it,
// so it is tighter than the detached ingest's description.
const imageAskTimeout = 60 * time.Second

const imageAskInstruction = "Answer the question below about this image precisely. " +
	"Read axes, ranges, scales, labels, legends and legible text as they appear; " +
	"say plainly what you cannot see or read. Plain prose, no preamble, no markdown.\n\nQuestion: "

// visionCall is one vision-model call about an image.
type visionCall struct {
	purpose string
	// verb and noun spell its errors; ingest records them on the document.
	verb, noun  string
	instruction string
	maxTokens   int
	timeout     time.Duration
	// reasoning is the effort: minimal for transcription, balanced where the
	// answer is prose another model acts on (minimal may mean thinking off).
	reasoning llmwire.ReasoningRequest
}

// DescribeImage returns a dense plain-text description of an image, generated by
// the vision model, for indexing the image as RAG knowledge. The text-only model
// 404s on image input, so this forces visionModel explicitly. The image is
// downscaled (imagescale) before being inlined as a base64 data URL.
func (c *Client) DescribeImage(ctx context.Context, data []byte, mime string) (string, error) {
	// The helper effort mirrors the title utility: deep thinking overthinks the
	// task and burns the token budget on reasoning (risking
	// finish_reason=length). Describing is perception + transcription, not
	// reasoning.
	return c.askVision(ctx, data, mime, visionCall{
		purpose:     "image_describe",
		verb:        "describe image",
		noun:        "image description",
		instruction: imageDescribeInstruction,
		maxTokens:   imageDescribeMaxCompletionTokens,
		timeout:     imageDescribeTimeout,
		reasoning:   llmwire.ReasoningMinimal(),
	})
}

// AskImage answers a question about an image with the vision model: how the
// chat model looks at a picture it made or was given, without the picture
// entering its own turn.
func (c *Client) AskImage(ctx context.Context, data []byte, mime, question string) (string, error) {
	// A turn's context names the turn's purpose: this call logs as its own.
	return c.askVision(inference.WithPurpose(ctx, "image_view"), data, mime, visionCall{
		purpose:     "image_view",
		verb:        "ask image",
		noun:        "image answer",
		instruction: imageAskInstruction + strings.TrimSpace(question),
		maxTokens:   imageAskMaxCompletionTokens,
		timeout:     imageAskTimeout,
		reasoning:   llmwire.ReasoningBalanced(),
	})
}

func (c *Client) askVision(ctx context.Context, data []byte, mime string, call visionCall) (string, error) {
	if imagescale.TooLarge(bytes.NewReader(data)) {
		return "", fmt.Errorf("%s: image has too many pixels", call.verb)
	}
	// Tag the call even when it runs from a path that attached no metadata (a
	// detached ingest goroutine), so the log line is never an anonymous
	// vision-model call.
	ctx = inference.WithDefaultPurpose(ctx, call.purpose)
	ctx, cancel := context.WithTimeout(ctx, call.timeout)
	defer cancel()

	encoded, encodedMIME := imagescale.DownscaleForModel(data, mime)
	dataURL := "data:" + encodedMIME + ";base64," + base64.StdEncoding.EncodeToString(encoded)

	messages := []Message{{
		Role: "user",
		ContentParts: []MessageContentPart{
			{Type: "image_url", ImageURL: &MessageImageURL{URL: dataURL}},
			{Type: "text", Text: call.instruction},
		},
	}}

	reply, err := c.complete(ctx, c.visionModel, messages, call.maxTokens, call.reasoning, nil)
	if err != nil {
		return "", err
	}
	if reply.Empty {
		return "", fmt.Errorf("%s returned no choices", call.noun)
	}
	text := strings.TrimSpace(reply.Content)
	if text == "" {
		// Empty content (e.g. finish_reason=length, or the model emitted only a
		// channel marker) → surface a clear error so ingest records status=error
		// instead of embedding nothing.
		return "", fmt.Errorf("%s was empty (finish_reason=%q)", call.noun, reply.FinishReason)
	}
	return text, nil
}
